class UserProfile:
    def __init__(self, age, gender, height, weight, health_goals, activity_level, work_schedule, sleep_patterns, dietary_preferences, medical_history, budget):
        self.age = age
        self.gender = gender
        self.height = height
        self.weight = weight
        self.health_goals = health_goals
        self.activity_level = activity_level
        self.work_schedule = work_schedule
        self.sleep_patterns = sleep_patterns
        self.dietary_preferences = dietary_preferences
        self.medical_history = medical_history
        self.budget = budget
